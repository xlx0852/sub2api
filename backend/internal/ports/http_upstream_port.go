package ports

import (
	"net/http"

	"github.com/Wei-Shaw/sub2api/internal/domain"
)

// HTTPUpstream 上游 HTTP 请求接口
// 用于向上游 API（Claude、OpenAI、Gemini 等）发送请求
type HTTPUpstream interface {
	// Do 执行 HTTP 请求（不启用 TLS 指纹）
	Do(req *http.Request, proxyURL string, accountID int64, accountConcurrency int) (*http.Response, error)

	// DoWithTLS 执行带 TLS 指纹伪装的 HTTP 请求
	//
	// profile 参数:
	//   - nil: 不启用 TLS 指纹，行为与 Do 方法相同
	//   - non-nil: 使用指定的 Profile 进行 TLS 指纹伪装
	DoWithTLS(req *http.Request, proxyURL string, accountID int64, accountConcurrency int, profile *domain.TLSFingerprintRuntimeProfile) (*http.Response, error)
}
